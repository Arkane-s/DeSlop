let currentLang = 'en';

async function i18nInit() {
  const { language } = await chrome.storage.local.get({ language: 'en' });
  currentLang = SUPPORTED_LANGS.includes(language) ? language : 'en';
  return currentLang;
}

function i18nGetLang() {
  return currentLang;
}

function i18nSetLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  chrome.storage.local.set({ language: lang });
}

function i18nOnChange(cb) {
  chrome.storage.onChanged.addListener((changes, area) => {
    if (area === 'local' && changes.language) {
      currentLang = SUPPORTED_LANGS.includes(changes.language.newValue) ? changes.language.newValue : 'en';
      if (cb) cb(currentLang);
    }
  });
}

function t(key, vars) {
  const dict = I18N_STRINGS[currentLang] || I18N_STRINGS.en;
  let str = dict[key];
  if (str === undefined) str = I18N_STRINGS.en[key] !== undefined ? I18N_STRINGS.en[key] : key;
  if (vars) {
    for (const k in vars) {
      str = str.split('{' + k + '}').join(vars[k]);
    }
  }
  return str;
}

function tType(code) {
  const dict = (I18N_STRINGS[currentLang] && I18N_STRINGS[currentLang].threatTypes) || {};
  return dict[code] || I18N_STRINGS.en.threatTypes[code] || code;
}

function tPlatform(code) {
  const dict = (I18N_STRINGS[currentLang] && I18N_STRINGS[currentLang].threatPlatforms) || {};
  return dict[code] || I18N_STRINGS.en.threatPlatforms[code] || code;
}